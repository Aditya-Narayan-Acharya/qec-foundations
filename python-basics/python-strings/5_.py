text = "Hello World"
print("original: ", text)
print("lower: ", text.lower())
print("original again: ", text)
print("upper: ", text.upper())

#strip function.
text = "      Hello World    "
print("original: ", text)
print("stripped: ", text.strip())
print("original again: ", text)
print("upper: ", text.upper().strip())


# replace function.
text = "Hello World"
print("original: ", text)
print("replaced: ",text.replace("Hello","goodbye"))
print("original again: ",text)


