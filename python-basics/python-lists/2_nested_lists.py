matrix = [
[1,2,3],
[4,5,6]
]

print(matrix)


# We can get individual objects within the nested list.
print(matrix[0])
print(matrix[-1])

#We can also index within the specific list of nested list.
print(matrix[0][1])    #This will give us first list's second object.
print(matrix[-1][-1])  #This will giive us last list's last object.

